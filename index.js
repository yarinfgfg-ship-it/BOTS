function giveawayWinnerCount(g) {
  if (Array.isArray(g.winners)) return g.winners.length;
  return Number(g.winners) || 1;
}

function giveawayEmbed(g) {
  const count = (g.entrants || []).length;
  const roleLine = g.roleId ? `\n🎭 דרישה: <@&${g.roleId}>` : '';
  const winnerCount = giveawayWinnerCount(g);
  let title = `🎉 ${g.prize}`;
  let description =
    `לחצו על הכפתור כדי להיכנס!\n\n👥 משתתפים: **${count}**\n` +
    `🏆 זוכים: **${winnerCount}**\n⏰ מסתיים: <t:${Math.floor(g.endsAt / 1000)}:R>${roleLine}`;

  if (g.ended) {
    if (g.cancelled) {
      title = fill(config.giveaway.cancelledTitle, { prize: g.prize });
      description = fill(config.giveaway.cancelledDescription, { count });
    } else {
      title = `🎉 ${g.prize} — הסתיים`;
      const winnerNames = Array.isArray(g.winners) && g.winners.length
        ? g.winners.map((id) => `<@${id}>`).join(', ')
        : config.giveaway.winnerListFallback;
      description = fill(config.giveaway.endedDescription, {
        count,
        winners: winnerNames,
        time: Math.floor((g.endedAt || Date.now()) / 1000),
      });
    }
  }

  const embed = new EmbedBuilder()
    .setColor(g.cancelled ? config.colors.closed : config.giveaway.color)
    .setTitle(title)
    .setDescription(description)
    .setFooter({ text: `מארח: ${g.hostTag || 'יוצר השרת'} · ${config.brand.footer}` })
    .setTimestamp();

  return brandEmbed(embed);
}

function giveawayComponents(g) {
  if (g.ended) return [];
  return [
    new ActionRowBuilder().addComponents(
      new ButtonBuilder()
        .setCustomId(`giveaway_enter:${g.id}`)
        .setLabel(config.giveaway.button)
        .setStyle(ButtonStyle.Success)
    ),
  ];
}

function pickWinners(entrants, count, excluded = []) {
  const pool = [...new Set(entrants)].filter((id) => !excluded.includes(id));
  const picked = [];
  while (picked.length < count && pool.length) {
    const [id] = pool.splice(crypto.randomInt(pool.length), 1);
    picked.push(id);
  }
  return picked;
}

async function announceWinners(channel, g, winnerIds, reroll = false) {
  for (const id of winnerIds) {
    const user = await client.users.fetch(id).catch(() => null);
    const name = user ? user.globalName || user.username : 'משתמש';

    const buffer = await buildWinnerCard({
      avatarUrl: user?.displayAvatarURL({ size: 512, extension: 'png' }),
      name,
      prize: g.prize,
      reroll,
    }).catch((err) => {
      console.error('[giveaway] card:', err.message);
      return null;
    });

    const embed = new EmbedBuilder()
      .setColor(config.giveaway.color)
      .setTitle(reroll ? config.giveaway.rerollTitle : config.giveaway.winnerTitle);

    const payload = { content: `<@${id}>`, allowedMentions: { parse: ['users'] } };

    if (buffer) {
      embed.setImage('attachment://winner.png');
      payload.files = [new AttachmentBuilder(buffer, { name: 'winner.png' })];
    } else {
      embed.setDescription(
        config.giveaway.winnerText
          .replace('{winner}', `<@${id}>`)
          .replace('{prize}', `**${g.prize}**`)
      );
    }

    payload.embeds = [embed];
    await channel.send(payload).catch(() => {});

    // Winner DM — same card, no server name, never blocks the announcement.
    if (user) {
      try {
        const dmPayload = {
          embeds: [
            new EmbedBuilder()
              .setColor(config.giveaway.color)
              .setTitle(config.giveaway.dmTitle)
              .setDescription(fill(config.giveaway.dmText, { prize: g.prize })),
          ],
        };
        if (buffer) {
          dmPayload.files = [new AttachmentBuilder(buffer, { name: 'winner.png' })];
        }
        await user.send(dmPayload);
      } catch (err) {
        console.error('[giveaway] winner DM:', err.message);
      }
    }
  }
}

async function refreshGiveawayMessage(g) {
  const channel = await client.channels.fetch(g.channelId).catch(() => null);
  if (!channel) return;
  const message = await channel.messages.fetch(g.messageId).catch(() => null);
  if (!message) return;
  try {
    await message.edit({ embeds: [giveawayEmbed(g)], components: giveawayComponents(g) });
  } catch {
    /* message may be gone */
  }
}

async function endGiveaway(id) {
  const g = giveaways.get(id);
  if (!g || g.ended) return;

  const winners = pickWinners(g.entrants || [], giveawayWinnerCount(g));
  giveaways.set(id, {
    ended: true,
    endedAt: Date.now(),
    winners,
    rerollWinners: [],
  });

  const channel = await client.channels.fetch(g.channelId).catch(() => null);
  if (!channel) return;

  const message = await channel.messages.fetch(g.messageId).catch(() => null);
  const ended = { ...g, ended: true, winners };
  if (message) {
    try {
      await message.edit({ embeds: [giveawayEmbed(ended)], components: [] });
    } catch {
      /* message may be gone */
    }
  }

  if (!winners.length) {
    try {
      await channel.send({ content: config.giveaway.noEntries });
    } catch {
      /* no permission */
    }
    return;
  }

  await announceWinners(channel, g, winners);
}

async function restoreGiveaways() {
  for (const g of Object.values(giveaways.all())) {
    if (g.ended) continue;
    const ms = Number(g.endsAt) - Date.now();
    if (ms <= 0) {
      await endGiveaway(g.id);
    } else {
      setTimeout(() => endGiveaway(g.id), ms);
    }
  }
}

async function createGiveaway(interaction) {
  const prize = interaction.options.getString('prize', true).trim();
  const minutes = interaction.options.getInteger('duration', true);
  const winners = interaction.options.getInteger('winners') || 1;
  const channel = interaction.options.getChannel('channel') || interaction.channel;
  const role = interaction.options.getRole('role');

  if (!channel?.isTextBased()) {
    return reply(interaction, { content: '⚠️ צריך לבחור ערוץ טקסט.' });
  }

  const id = `gw_${Date.now()}_${crypto.randomBytes(3).toString('hex')}`;
  const g = {
    id,
    guildId: interaction.guild.id,
    channelId: channel.id,
    prize,
    winners,
    endsAt: Date.now() + minutes * 60_000,
    roleId: role?.id || null,
    entrants: [],
    ended: false,
    hostId: interaction.user.id,
    hostTag: interaction.user.tag,
  };

  giveaways.set(id, g);

  let message;
  try {
    message = await channel.send({ embeds: [giveawayEmbed(g)], components: giveawayComponents(g) });
  } catch (err) {
    giveaways.remove(id);
    console.error('[giveaway] send:', err.message);
    return reply(interaction, { content: '❌ אין לי הרשאה לשלוח בערוץ הזה.' });
  }

  giveaways.set(id, { messageId: message.id });
  setTimeout(() => endGiveaway(id), minutes * 60_000);

  return reply(interaction, {
    content: `✅ ההגרלה נוצרה בערוץ <#${channel.id}>.\nמזהה הודעה: \`${message.id}\``,
  });
}

async function enterGiveaway(interaction) {
  const id = interaction.customId.slice('giveaway_enter:'.length);
  const g = giveaways.get(id);

  if (!g || g.ended) {
    return interaction.reply({ content: '⚠️ ההגרלה כבר הסתיימה.', ephemeral: true }).catch(() => {});
  }

  if (g.roleId && !interaction.member?.roles?.cache?.has(g.roleId)) {
    return interaction.reply({ content: config.giveaway.roleRequired, ephemeral: true }).catch(() => {});
  }

  const entrants = new Set(g.entrants || []);
  if (entrants.has(interaction.user.id)) {
    return interaction.reply({ content: config.giveaway.already, ephemeral: true }).catch(() => {});
  }

  entrants.add(interaction.user.id);
  giveaways.set(id, { entrants: [...entrants] });

  await interaction.reply({ content: config.giveaway.entered, ephemeral: true }).catch(() => {});
  await refreshGiveawayMessage({ ...g, entrants: [...entrants] });
}

async function giveawayByMessage(interaction) {
  const messageId = interaction.options.getString('id', true).trim();
  return Object.values(giveaways.all()).find(
    (g) => g.messageId === messageId && g.guildId === interaction.guild.id
  );
}

async function rerollGiveaway(interaction) {
  const g = await giveawayByMessage(interaction);
  if (!g) return reply(interaction, { content: '⚠️ לא נמצאה הגרלה עם המזהה הזה.' });
  if (!g.ended) return reply(interaction, { content: config.giveaway.alreadyEnded });

  const requested = Math.max(1, Math.min(10, interaction.options.getInteger('count') || 1));
  // Original winners and everyone picked by earlier rerolls must not win again.
  const excluded = [
    ...(g.rerollWinners || []),
    ...(Array.isArray(g.winners) ? g.winners : []),
  ];
  const winners = pickWinners(g.entrants || [], requested, excluded);
  if (!winners.length) return reply(interaction, { content: config.giveaway.noReroll });

  giveaways.set(g.id, {
    rerollWinners: [...new Set([...excluded, ...winners])],
  });

  const channel = await client.channels.fetch(g.channelId).catch(() => null);
  if (channel) await announceWinners(channel, g, winners, true);

  return reply(interaction, {
    content: fill(config.giveaway.rerollDone, { count: winners.length }),
  });
}

async function cancelGiveaway(interaction) {
  const g = await giveawayByMessage(interaction);
  if (!g) return reply(interaction, { content: '⚠️ לא נמצאה הגרלה עם המזהה הזה.' });
  if (g.ended) return reply(interaction, { content: config.giveaway.alreadyEnded });

  const cancelled = {
    ...g,
    ended: true,
    cancelled: true,
    endedAt: Date.now(),
    winners: [],
  };
  giveaways.set(g.id, {
    ended: true,
    cancelled: true,
    endedAt: cancelled.endedAt,
    winners: [],
  });

  const channel = await client.channels.fetch(g.channelId).catch(() => null);
  const message = channel ? await channel.messages.fetch(g.messageId).catch(() => null) : null;
  if (message) {
    await message
      .edit({ embeds: [giveawayEmbed(cancelled)], components: [] })
      .catch(() => {});
  }

  return reply(interaction, { content: config.giveaway.cancelledDone });
}

