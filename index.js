function voteBar(up, down, size = 12) {
  const total = up + down;
  const upPart = total ? Math.round((up / total) * size) : 0;
  return '🟩'.repeat(upPart) + '⬜'.repeat(size - upPart);
}

function suggestionEmbed(s) {
  const up = s.votes?.up || 0;
  const down = s.votes?.down || 0;
  const total = up + down;
  const upPct = total ? Math.round((up / total) * 100) : 0;
  const downPct = total ? 100 - upPct : 0;

  const status =
    s.status === 'approved'
      ? config.community.statusApproved
      : s.status === 'denied'
        ? config.community.statusDenied
        : config.community.statusOpen;
  const color =
    s.status === 'approved' ? '#57F287' : s.status === 'denied' ? '#ED4245' : config.community.color;
  const autoLine =
    s.endsAt && s.status === 'open'
      ? `\n${config.community.autoTime.replace('{time}', Math.floor(s.endsAt / 1000))}`
      : '';

  const votesText = config.community.votes
    .replace('{up}', up)
    .replace('{down}', down)
    .replace('{upPct}', upPct)
    .replace('{downPct}', downPct)
    .replace('{bar}', voteBar(up, down));

  return new EmbedBuilder()
    .setColor(color)
    .setAuthor({ name: config.community.suggestionTitle, iconURL: client.user?.displayAvatarURL() })
    .setDescription(`> ${s.text}`)
    .addFields(
      { name: config.community.suggestionStatusLabel, value: status + autoLine, inline: true },
      { name: config.community.suggestionVotesLabel, value: votesText, inline: true },
      {
        name: config.community.suggestionByLabel,
        value: config.community.suggestionBy.replace('{user}', `<@${s.authorId}>`),
        inline: false,
      }
    )
    .setFooter({ text: config.community.suggestionFooter.replace('{id}', s.id.slice(-6)) })
    .setTimestamp(new Date(s.createdAt || Date.now()));
}

