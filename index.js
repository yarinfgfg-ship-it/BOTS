function sanitizeTicketName(raw) {
  // Hebrew (and other Unicode) letters are valid in Discord channel names —
  // keep them so a typed name actually shows up in the channel.
  return String(raw || '')
    .normalize('NFKC')
    .replace(/\s+/g, '-')
    .replace(/[^\p{L}\p{N}_-]/gu, '')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40) || 'ticket';
}

